`timescale 1ns / 1ps
// ============================================================================
// curtain_wipe — 幕布收起/展开转场几何与遮罩 (纯组合; ctrl 域)
//
// 设计: doc 交付转向 2026-09-29 (交付目标降为"稳定的一级/二级切换动画",
//   绕开 A 类实时缩放与 bank/hint 路径, 复用已验证的静态图墙/满屏路径)。
//
// 效果:
//   进入二级: 静态图墙 → 上下两片幕布向中间合拢(~8 帧) → 全黑(交接到目标
//     满屏) → 幕布向上下展开(~8 帧) → 正确满屏。
//   返回一级: 满屏 → 合拢(~8 帧) → 全黑(交接回图墙) → 展开(~8 帧) → 图墙。
//   运动合计 ~16 帧 ≈ 0.27s; 全黑停留 = 交接真正就绪(不硬编码固定帧数)。
//
// 遮罩语义(关键): 被幕布遮住的像素(幕布区域内)输出"分隔带黑"响应
//   (en=0, tag=2'b00, data=0) —— 与现有墙分隔带同色, FE 以 en=0 数据=0
//   写入 FIFO ⇒ 每帧 307200 个响应位置守恒, 不引入位置错位。
//   遮罩不做"暂停消费/暂停 FIFO" —— 被遮像素仍产生 en0 响应。
//
// 几何: curt_h = 幕布半高(0..240, 每步 ~30)。幕布区 = py < curt_h ||
//   py >= 480 - curt_h。全黑时 curt_h >= 240。
//   幕布边界与像素流对齐: 由顶层在 VS 帧边界更新 curt_step。
//
// 端口语义:
//   输入显示行 py + 幕布激活标志 + 半高 curt_h; 输出 in_curt(该行在幕布区)。
//   幕布为整幅水平带, 与列无关, 故不设 px 端口。顶层据此把 comp_en/comp_tag
//   置 0/00(黑)。
// ============================================================================
module curtain_wipe (
    input  wire [11:0] py,           // 显示像素行 (0..479)
    input  wire        curt_active,  // 幕布状态机激活(合拢/全黑交接/展开中)
    input  wire [8:0]  curt_h,       // 幕布半高 0..240 (=240 全黑)

    output wire        in_curt       // 本像素在幕布区内(应输出黑)
);
    wire [11:0] h_lo = {3'b000, curt_h};        // 下边界(上片底边)
    wire [11:0] h_hi = 12'd480 - h_lo;          // 上边界(下片顶边)

    assign in_curt = curt_active &&
                     (curt_h >= 9'd240 ||
                      (py < h_lo) || (py >= h_hi));
endmodule
